"""build_site.py: assemble the site in docs/ from the repository. Run after the example scripts:

    python tools/build_site.py

1. Copies the style files into docs/ (the web reads docs/assets/vellum.json; docs/downloads/ serves every file and a zip),
   and writes docs/assets/css/vellum-tokens.css from style/vellum.css plus a no-script dark block.
2. Copies the data the interactive figures read into docs/data/.
3. Makes a 720 px WebP thumbnail of every figure in every docs/figures/*/manifest.json.
4. Fills the marked blocks of every page in docs/*.html: the shared head, header and footer from tools/partials/,
   the gallery (<!--#gallery-->), and single figures (<!--#fig group/id [class]-->). Running it twice changes nothing.
"""
import html, json, os, re, shutil, subprocess, zipfile
from PIL import Image
import site_blocks as blocks
import site_icons as icons

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DOCS = os.path.join(REPO, "docs")
PARTIALS = os.path.join(REPO, "tools", "partials")
GH = "https://github.com/akaminas/vellum"
STYLE_FILES = ["vellum.json", "vellum.py", "vellum.mplstyle", "vellum.R", "vellum-colors.sty", "vellum.css", "vellum-office.tsv", "vellum-web.js"]
WEB_DATA = ["penguins.json", "co2-concentration.csv", "owid-life-expectancy.csv", "disasters.csv", "miserables.json",
            "cars.json", "gapminder.json", "driving.json"]
KINDS = [("composite", "Composite"), ("map", "Maps"), ("scientific", "Scientific"), ("3d", "3D"), ("colour", "Colour"), ("report", "Report"), ("conference", "Conference"),
         ("infographic", "Infographic"), ("slides", "Slides"), ("tools", "LaTeX and R"), ("interactive", "Interactive")]
e = html.escape


def git(*args):
    return subprocess.run(["git", "-C", REPO, *args], capture_output=True, text=True).stdout.strip()


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f: f.write(text)


# ---------------------------------------------------------------- 1. style files

def style():
    src = os.path.join(REPO, "style")
    shutil.copy(os.path.join(src, "vellum.json"), os.path.join(DOCS, "assets", "vellum.json"))
    shutil.copy(os.path.join(src, "vellum-web.js"), os.path.join(DOCS, "assets", "js", "vellum-web.js"))
    dl = os.path.join(DOCS, "downloads"); os.makedirs(dl, exist_ok=True)
    with zipfile.ZipFile(os.path.join(dl, "vellum-style.zip"), "w", zipfile.ZIP_DEFLATED) as z:
        for f in STYLE_FILES:
            shutil.copy(os.path.join(src, f), os.path.join(dl, f)); z.write(os.path.join(src, f), f"vellum/{f}")
    # the tokens: light under :root, dark under [data-theme="dark"], and the dark block again for a reader without scripts
    css = open(os.path.join(src, "vellum.css"), encoding="utf-8").read()
    dark = re.search(r':root\[data-theme="dark"\], \.theme-dark \{(.*?)\}', css, re.S).group(1)
    # the lagoon stops as variables too, for the site's icons of a surface (the gradient used as the data scale it is)
    lagoon = json.load(open(os.path.join(src, "vellum.json"), encoding="utf-8"))["gradients"]["lagoon"]
    lag = lambda m: "".join(f"  --v-lagoon-{i + 1}: {h};\n" for i, h in enumerate(lagoon[m]))
    css += ":root {\n" + lag("light") + "}\n:root[data-theme=\"dark\"] {\n" + lag("dark") + "}\n"
    write(os.path.join(DOCS, "assets", "css", "vellum-tokens.css"),
          "/* Generated by tools/build_site.py from style/vellum.css. Do not edit. Light is the default; dark is a choice. */\n" + css)


# ---------------------------------------------------------------- 2. data

def data():
    out = os.path.join(DOCS, "data"); os.makedirs(out, exist_ok=True)
    for f in WEB_DATA:
        shutil.copy(os.path.join(REPO, "data", f), os.path.join(out, f))
    shutil.copy(os.path.join(REPO, "data", "SOURCES.md"), os.path.join(out, "SOURCES.md"))


# ---------------------------------------------------------------- 3. manifests and thumbnails

def manifests():
    items = []
    figs = os.path.join(DOCS, "figures")
    for group in sorted(os.listdir(figs)):
        p = os.path.join(figs, group, "manifest.json")
        if os.path.exists(p):
            items += json.load(open(p, encoding="utf-8"))
    order = {k: i for i, (k, _) in enumerate(KINDS)}
    return sorted(items, key=lambda it: order.get(it.get("kind"), 99))


def thumb(rel_png, width=720):
    """docs-relative path of a WebP thumbnail of a docs-relative PNG, made if missing or stale."""
    if not rel_png: return None
    src = os.path.join(DOCS, rel_png)
    if not os.path.exists(src): return None
    d, f = os.path.split(rel_png)
    rel = f"{d}/thumbs/{os.path.splitext(f)[0]}{'' if width == 720 else f'.w{width}'}.webp"
    dst = os.path.join(DOCS, rel)
    if not os.path.exists(dst) or os.path.getmtime(dst) < os.path.getmtime(src):
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        try: im = Image.open(src).convert("RGB")
        except OSError: return None          # an image still being written: skip it this time
        if im.width > width: im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
        im.save(dst, "WEBP", quality=86, method=4)
    return rel


def crop(rel_png, width=720):
    """docs-relative path of a 3:2 detail crop of a figure, for the mosaic and the works grid. A figure's title block and
    footer are text, which a tile cannot show legibly, so the window sits on the data: below the top fifth and above the
    footer of a landscape figure, in the upper middle of a portrait page. The tile's caption carries the title."""
    if not rel_png: return None
    src = os.path.join(DOCS, rel_png)
    if not os.path.exists(src): return None
    d, f = os.path.split(rel_png)
    rel = f"{d}/thumbs/{os.path.splitext(f)[0]}.crop.webp"
    dst = os.path.join(DOCS, rel)
    if not os.path.exists(dst) or os.path.getmtime(dst) < os.path.getmtime(src):
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        try: im = Image.open(src).convert("RGB")
        except OSError: return None
        W, H = im.size
        if W / H > 1.2:   # a landscape figure: a window 72 % of the width, centred on the plot area
            w = 0.72 * W; h = w / 1.5
            if h > 0.74 * H: h = 0.74 * H; w = 1.5 * h
            cx, cy = W / 2, H * 0.56
        else:             # a portrait page or a square sheet: the upper middle
            w = 0.92 * W; h = w / 1.5; cx, cy = W / 2, H * 0.38
        box = (max(0, cx - w / 2), max(0, min(H - h, cy - h / 2)))
        im = im.crop((round(box[0]), round(box[1]), round(box[0] + w), round(box[1] + h)))
        im.resize((width, round(width / 1.5)), Image.LANCZOS).save(dst, "WEBP", quality=86, method=4)
    return rel


def exists(rel):
    return bool(rel) and os.path.exists(os.path.join(DOCS, rel))


def twin_imgs(it, cls="", use_thumb=False):
    """Both twins of a figure as two <img>, the page showing the one that matches the theme. One image if one twin."""
    f = it.get("files", {})
    light, dark = f.get("light"), f.get("dark")
    if not exists(dark): dark = None
    alt = e(it.get("alt") or it.get("title", ""), quote=True)
    cap = e(it.get("title", ""), quote=True)
    out = []
    for mode, src in (("light", light), ("dark", dark)):
        if not exists(src): continue
        shown = thumb(src) if use_thumb else src
        twin = f" twin-{mode}" if dark else ""
        out.append(f'<img class="zoom{twin} {cls}" src="{shown}" data-full="{src}" data-caption="{cap}" alt="{alt}" loading="lazy" decoding="async">')
    return "".join(out)


def links(it):
    f = it.get("files", {})
    out = []
    if exists(f.get("light")): out.append(f'<a href="{f["light"]}">PNG</a>')
    if exists(f.get("dark")): out.append(f'<a href="{f["dark"]}">PNG, dark</a>')
    if exists(f.get("pdf")): out.append(f'<a href="{f["pdf"]}">PDF</a>')
    if exists(f.get("html")): out.append(f'<a href="{f["html"]}">Open the page</a>')
    if it.get("script"): out.append(f'<a href="{GH}/blob/main/{it["script"]}">Script</a>')
    if it.get("href"): out.append(f'<a href="{it["href"]}">Open</a>')
    return '<p class="fig-links">' + " ".join(out) + "</p>"


def figure_block(it, cls=""):
    # the figure carries its own claim, units and source; the caption only gives the files
    body = twin_imgs(it)
    cap = []
    parts = ""
    if it.get("parts"):
        parts = '<ol class="parts small">' + "".join(f"<li>{e(p)}</li>" for p in it["parts"]) + "</ol>"
    return (f'<figure class="figure {cls}" id="fig-{it["group"]}-{it["id"]}"><div class="frame">{body}</div>'
            f'<figcaption>{"<br>".join(cap)}{links(it)}</figcaption>{parts}</figure>')


BADGES = {  # a small badge in the corner of a tile, after the trophies on Visual Cinnamon's works grid
    "interactive": '<path d="M5 3l12 6-5 2-2 5z"/><path d="M12 11l6 6"/>',
    "3d": '<path d="M12 3l8 4.5v9L12 21l-8-4.5v-9z"/><path d="M12 12l8-4.5M12 12v9M12 12L4 7.5"/>',
    "pages": '<rect x="6" y="4" width="12" height="16" rx="1.5"/><path d="M9 9h6M9 12h6M9 15h4"/>',
}


def target_of(it):
    """Where a tile leads: the interactive page, the media page for a multi-page piece, or None for the lightbox."""
    if it["group"] == "interactive": return f'interactive.html#{it["id"]}'
    if it.get("files", {}).get("pages"): return f'media.html#{it["id"]}'
    return None


def link_list(it):
    f = it.get("files", {}); out = []
    target = target_of(it)
    if target: out.append(["Open " + ("the interactive" if it["group"] == "interactive" else "all pages"), target])
    if exists(f.get("light")): out.append(["PNG", f["light"]])
    if exists(f.get("dark")): out.append(["PNG, dark", f["dark"]])
    if exists(f.get("pdf")): out.append(["PDF", f["pdf"]])
    if exists(f.get("pptx")): out.append(["PowerPoint", f["pptx"]])
    if exists(f.get("pptx_dark")): out.append(["PowerPoint, dark", f["pptx_dark"]])
    if it.get("script"): out.append(["Script", f"{GH}/blob/main/{it['script']}"])
    return out


# the page of a multi-page piece that stands for it on a tile: a page with a figure, not the title page
COVERS = {"talk/talk": "media/talk/talk-08.png", "pitch/pitch": "media/pitch/slide-05.png", "report/report": "media/report/page-2.png"}


def tile_imgs(it, zoom, only=None, full=False, width=720):
    """The detail crops of both twins (or of the one image a piece has). only="light" or "dark" fixes one twin."""
    f = it.get("files", {})
    cover = COVERS.get(f'{it["group"]}/{it["id"]}')
    light = cover if exists(cover) else f.get("light") if exists(f.get("light")) else (f.get("pages") or [None])[0]
    dark = f.get("dark") if exists(f.get("dark")) and not cover else None
    if only == "dark" and dark: light, dark = dark, None
    elif only: dark = None
    alt = e(it.get("alt") or it.get("title", ""), quote=True)
    extra = (f' data-caption="{e(it.get("title", ""), quote=True)}" data-links="{e(json.dumps(link_list(it)), quote=True)}"') if zoom else ""
    out = []
    for mode, src in (("light", light), ("dark", dark)):
        if not exists(src): continue
        cls = ("zoom " if zoom else "") + (f"twin-{mode}" if dark else "")
        out.append(f'<img class="{cls.strip()}" src="{thumb(src, width) if full else crop(src)}" data-full="{src}"{extra} alt="{alt}" loading="lazy" decoding="async">')
    return "".join(out)


def caption(it):
    kind = " · ".join(t for t in (it.get("form"), it.get("tool")) if t)
    return f'<span class="tile-cap"><small>{e(kind)}</small>{e(it.get("title", ""))}</span>'


def badge(it):
    key = "interactive" if it["group"] == "interactive" else "3d" if it.get("kind") == "3d" else "pages" if it.get("files", {}).get("pages") else None
    if not key: return ""
    return f'<span class="badge" aria-hidden="true"><svg viewBox="0 0 24 24">{BADGES[key]}</svg></span>'


def kinds_of(it):
    """The gallery categories of a piece: its kind, and "infographic" too when its medium is an infographic."""
    out = [it.get("kind", "")]
    if it.get("medium") == "infographic" and "infographic" not in out: out.append("infographic")
    return out


def gallery(items):
    counts = {k: sum(1 for it in items if k in kinds_of(it)) for k, _ in KINDS}
    chips = ['<button class="chip" type="button" data-filter="all" aria-pressed="true">All <span class="muted">' + str(len(items)) + "</span></button>"]
    for k, label in KINDS:
        if counts[k]:
            chips.append(f'<button class="chip" type="button" data-filter="{k}" aria-pressed="false">{label} <span class="muted">{counts[k]}</span></button>')
    works = []
    for it in items:
        tile = f'<div class="work-tile">{tile_imgs(it, True, full=True)}{caption(it)}</div>'
        works.append(f'<figure class="work" data-kind="{e(" ".join(kinds_of(it)))}" id="g-{it["group"]}-{it["id"]}">{tile}{badge(it)}</figure>')
    return ('<div class="filter-row center" role="group" aria-label="Filter the gallery">' + "".join(chips) + "</div>"
            '<p class="sr-only" aria-live="polite" id="gallery-status"></p>'
            '<div class="works">' + "".join(works) + "</div>")


def mosaic(keys, by_id):
    """The selected works: image-led tiles in the twin that matches the theme, the title shown on hover."""
    tiles = []
    for key in keys:
        it = by_id.get(key)
        if not it: continue
        href = target_of(it) or f'gallery.html#g-{it["group"]}-{it["id"]}'
        tiles.append(f'<div class="sel-tile">{tile_imgs(it, True, full=True)}{caption(it)}</div>')
    return '<div class="selected">' + "".join(tiles) + "</div>"


def pair(keys, by_id):
    """One work shown in both twins side by side, whatever the theme, large, each opening in the lightbox."""
    it = by_id.get(keys[0])
    if not it: return ""
    tiles = [f'<div class="sel-tile">{tile_imgs(it, True, only=mode, full=True, width=1400)}</div>' for mode in ("light", "dark")]
    # on the first screen: load at once, not lazily
    return '<div class="pair">' + "".join(tiles).replace('loading="lazy"', 'loading="eager" fetchpriority="high"') + "</div>"


def strip(keys, by_id):
    """A full-width band of detail crops for the top of the home page, no captions."""
    tiles = []
    for key in keys:
        it = by_id.get(key)
        if not it: continue
        href = target_of(it) or f'gallery.html#g-{it["group"]}-{it["id"]}'
        tiles.append(f'<a href="{href}" tabindex="-1" aria-hidden="true">{tile_imgs(it, False)}</a>')
    return '<div class="strip bleed">' + "".join(tiles) + "</div>"


# ---------------------------------------------------------------- 4. pages

def fill(text, name, content):
    return re.sub(rf"(<!--#{name}-->).*?(<!--/{name}-->)", lambda m: m.group(1) + "\n" + content + "\n" + m.group(2), text, flags=re.S)


def pages(items):
    by_id = {f'{it["group"]}/{it["id"]}': it for it in items}
    stamp = git("rev-parse", "--short", "HEAD") or "unstamped"
    part = {n: open(os.path.join(PARTIALS, f"{n}.html"), encoding="utf-8").read().strip() for n in ("head", "header", "footer")}
    part["footer"] = part["footer"].replace("{{STAMP}}", stamp)
    missing = []
    for fn in sorted(os.listdir(DOCS)):
        if not fn.endswith(".html"): continue
        p = os.path.join(DOCS, fn); t = open(p, encoding="utf-8").read()
        for n in ("head", "header", "footer"): t = fill(t, n, part[n])
        if "<!--#gallery-->" in t: t = fill(t, "gallery", gallery(items))
        t = re.sub(r"<!--#pair ([^>]+?)-->.*?<!--/pair-->",
                   lambda m: f"<!--#pair {m.group(1)}-->\n{pair(m.group(1).split(), by_id)}\n<!--/pair-->", t, flags=re.S)
        t = re.sub(r"<!--#strip ([^>]+?)-->.*?<!--/strip-->",
                   lambda m: f"<!--#strip {m.group(1)}-->\n{strip(m.group(1).split(), by_id)}\n<!--/strip-->", t, flags=re.S)
        t = re.sub(r"<!--#mosaic ([^>]+?)-->.*?<!--/mosaic-->",
                   lambda m: f"<!--#mosaic {m.group(1)}-->\n{mosaic(m.group(1).split(), by_id)}\n<!--/mosaic-->", t, flags=re.S)
        if "<!--#formsindex-->" in t: t = fill(t, "formsindex", icons.index(by_id))

        def fig(m):
            key, cls = m.group(1), (m.group(2) or "").strip()
            it = by_id.get(key)
            if not it:
                missing.append(f"{fn}: {key}"); return m.group(0)
            return f"<!--#fig {key}{(' ' + cls) if cls else ''}-->\n{figure_block(it, cls)}\n<!--/fig-->"
        t = re.sub(r"<!--#fig ([\w\-]+/[\w\-]+)( [\w\- ]+)?-->.*?<!--/fig-->", fig, t, flags=re.S)

        def viewer(m):
            key = m.group(1); it = by_id.get(key)
            if not it or not it.get("files", {}).get("pages"):
                missing.append(f"{fn}: viewer {key}"); return m.group(0)
            pages_json = e(json.dumps(it["files"]["pages"]), quote=True)
            alt = e(it.get("alt") or it.get("title", ""), quote=True)
            first = os.path.join(DOCS, it["files"]["pages"][0])
            try: w, h = Image.open(first).size
            except OSError: w, h = 16, 9
            stage = f"aspect-ratio:{w}/{h}" + (";max-width:620px;margin:0 auto" if h > w else "")
            block = (f'<div class="viewer" data-pages="{pages_json}" data-alt="{e(it.get("form", "Page"), quote=True)}" aria-label="{alt}">'
                     f'<div class="viewer-stage" style="{stage}"><img alt=""></div><div class="viewer-bar">'
                     '<button class="btn prev" type="button">Previous</button><span class="viewer-count"></span>'
                     '<button class="btn next" type="button">Next</button></div><div class="viewer-strip"></div></div>'
                     f'<div class="fig-meta">{e(it.get("data", ""))}{" · " + e(it["note"]) if it.get("note") else ""}{links(it)}</div>')
            return f"<!--#viewer {key}-->\n{block}\n<!--/viewer-->"
        t = re.sub(r"<!--#viewer ([\w\-]+/[\w\-]+)-->.*?<!--/viewer-->", viewer, t, flags=re.S)
        t = re.sub(r"(<!--#table (\w+)-->).*?(<!--/table-->)", lambda m: m.group(1) + "\n" + blocks.BLOCKS[m.group(2)]() + "\n" + m.group(3), t, flags=re.S)
        if "<!--#wheel-->" in t: t = fill(t, "wheel", blocks.wheel())
        if "<!--#lightness-->" in t: t = fill(t, "lightness", blocks.lightness())
        t = re.sub(r"(<!--#count (\w+)-->).*?(<!--/count-->)",
                   lambda m: m.group(1) + str(len(items) if m.group(2) == "all" else sum(1 for it in items if it.get("kind") == m.group(2))) + m.group(3), t, flags=re.S)
        write(p, t)
    for m in missing: print("missing figure:", m)


if __name__ == "__main__":
    style(); data()
    items = manifests()
    pages(items)
    print(f"built: {len(items)} gallery items")
